// Run: npm test (or node --test "test/*.test.mjs")
// tools/changelog.mjs writes docs/CHANGELOG.md from the git history. CI clones one commit deep, so the
// generator is checked on a scratch repo, and the committed file only against itself.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { commits, render } from '../tools/changelog.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');

function commit(dir, subject, day, extra = []) {
  const env = { ...process.env, GIT_AUTHOR_DATE: `${day}T12:00:00Z`, GIT_COMMITTER_DATE: `${day}T12:00:00Z` };
  const r = spawnSync('git', ['-c', 'user.name=t', '-c', 'user.email=t@example.invalid', 'commit', '-q', '--allow-empty', '-m', subject, ...extra], { cwd: dir, env, encoding: 'utf8' });
  assert.equal(r.status, 0, r.stderr);
}

test('changelog: non-merge commits newest first, grouped by day, subjects whole, the same text twice', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'skchangelog-'));
  assert.equal(spawnSync('git', ['init', '-q', '-b', 'main'], { cwd: dir }).status, 0);
  commit(dir, 'first', '2026-10-06');
  commit(dir, 'gate matcher Skill|Agent (#12)', '2026-10-06');
  spawnSync('git', ['checkout', '-q', '-b', 'side'], { cwd: dir });
  commit(dir, 'on a branch', '2026-10-07');
  spawnSync('git', ['checkout', '-q', 'main'], { cwd: dir });
  const env = { ...process.env, GIT_AUTHOR_DATE: '2026-10-08T12:00:00Z', GIT_COMMITTER_DATE: '2026-10-08T12:00:00Z' };
  assert.equal(spawnSync('git', ['-c', 'user.name=t', '-c', 'user.email=t@example.invalid', 'merge', '-q', '--no-ff', '-m', 'Merge side', 'side'], { cwd: dir, env }).status, 0);
  const list = commits(dir);
  assert.deepEqual(list.map((c) => c.subject), ['on a branch', 'gate matcher Skill|Agent (#12)', 'first'], 'no merge commit; a | stays in the subject');
  const text = render(list, 'abc1234');
  assert.equal(render(commits(dir), 'abc1234'), text, 'deterministic');
  const body = text.slice(text.indexOf('\n## '));
  assert.equal(body, `\n## 2026-10-07\n\n- on a branch (\`${list[0].hash}\`)\n\n## 2026-10-06\n\n- gate matcher Skill|Agent (#12) (\`${list[1].hash}\`)\n- first (\`${list[2].hash}\`)\n`);
  assert.match(text, /at `abc1234` \(3 commits, 2026-10-06 to 2026-10-07\)/);
  assert.match(text, /^# Changelog\n/);
});

test('changelog: the committed file lists as many commits as its header says, and was not edited by hand', () => {
  const text = fs.readFileSync(path.join(ROOT, 'docs', 'CHANGELOG.md'), 'utf8').replace(/\r\n/g, '\n');
  const m = /Generated by `node tools\/changelog\.mjs` from `git log --no-merges` at `([0-9a-f]{7,})` \((\d+) commits, (\S+) to (\S+)\)\./.exec(text);
  assert.ok(m, 'the header names the generator, the ref and the count');
  const bullets = text.split('\n').filter((l) => l.startsWith('- '));
  assert.equal(bullets.length, Number(m[2]));
  assert.ok(bullets.every((l) => /\(`[0-9a-f]{7,}`\)$/.test(l)), 'every entry ends in its hash');
  const days = text.split('\n').filter((l) => l.startsWith('## ')).map((l) => l.slice(3));
  assert.deepEqual([days.at(-1), days[0]], [m[3], m[4]]);
  assert.deepEqual(days, [...days].sort().reverse(), 'newest first');
});
