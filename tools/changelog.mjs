#!/usr/bin/env node
// docs/CHANGELOG.md from the git history: every non-merge commit up to a ref, newest first, grouped by the
// day it was committed, the subject as written and the short hash. No release tags exist, so there is no
// other grouping to read. The output depends on the ref alone, so running it twice at one commit gives
// the same file.
//
//   node tools/changelog.mjs [--ref <ref>] [--check]
//
// --check writes nothing and exits 1 when the file differs from what the ref gives. A commit cannot list
// itself, so the file is regenerated at the parent of the commit that adds it (or later, by the next one).
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const FILE = path.join(ROOT, 'docs', 'CHANGELOG.md');

const INTRO = `# Changelog

Every change to speckit-agents from the first commit to the latest, newest first. No release
tags exist yet, so entries are grouped by the day each commit was made. Merge commits are left
out; each pull request's commits appear under their own dates, and the PR number is in the
subject where the commit carries one.
`;

// The commits up to `ref` as { day, hash, subject }, newest first. A field separator that cannot appear in
// a subject: git strips control characters from %s except this one, which it passes through.
export function commits(cwd, ref = 'HEAD') {
  const r = spawnSync('git', ['log', '--no-merges', '--abbrev=7', '--format=%cs%x1f%h%x1f%s', ref], { cwd, encoding: 'utf8' });
  if (r.status !== 0) throw new Error(`git log ${ref}: ${r.stderr.trim()}`);
  return r.stdout.split('\n').filter(Boolean).map((l) => { const [day, hash, subject] = l.split('\x1f'); return { day, hash, subject }; });
}

export function render(list, ref) {
  if (!list.length) throw new Error('no commits');
  const out = [INTRO, `Generated by \`node tools/changelog.mjs\` from \`git log --no-merges\` at \`${ref}\` (${list.length} commits, `
    + `${list.at(-1).day} to ${list[0].day}). Subjects are copied as written. Re-generate it rather than editing it by hand.\n`];
  let day = null;
  for (const c of list) {
    if (c.day !== day) { out.push(`${day === null ? '' : '\n'}## ${c.day}\n`); day = c.day; }
    out.push(`- ${c.subject} (\`${c.hash}\`)`);
  }
  return `${out.join('\n')}\n`;
}

function main(argv) {
  let ref = 'HEAD';
  let check = false;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--ref') ref = argv[++i];
    else if (argv[i] === '--check') check = true;
    else throw new Error(`unknown argument ${argv[i]}; usage: node tools/changelog.mjs [--ref <ref>] [--check]`);
  }
  const short = spawnSync('git', ['rev-parse', '--short=7', ref], { cwd: ROOT, encoding: 'utf8' }).stdout.trim();
  const text = render(commits(ROOT, ref), short || ref);
  if (check) {
    const now = fs.existsSync(FILE) ? fs.readFileSync(FILE, 'utf8').replace(/\r\n/g, '\n') : '';
    if (now !== text) { console.log(`docs/CHANGELOG.md differs from what ${ref} gives: run node tools/changelog.mjs --ref ${ref}`); process.exit(1); }
    console.log(`docs/CHANGELOG.md matches ${ref}`);
    return;
  }
  fs.writeFileSync(FILE, text);
  console.log(`docs/CHANGELOG.md: ${text.split('\n').filter((l) => l.startsWith('- ')).length} commits up to ${short || ref}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main(process.argv.slice(2)); } catch (e) { console.error(`changelog: ${e.message}`); process.exit(2); }
}
